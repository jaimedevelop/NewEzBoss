export function routeLocation(pathname: string) {
    const entries = Object.entries(routeLocations).sort((a, b) => b[0].split('/').length - a[0].split('/').length);
    const path = pathname.replace(/^\//, '').replace(/\/$/, '');
    const exact = entries.find(([pattern]) => new RegExp('^' + pattern.replace(/:[^/]+/g, '[^/]+') + '$').test(path));
    if (exact)
        return { page: '/' + exact[0], label: exact[1] };
    const base = entries.find(([pattern]) => !pattern.includes(':') && path.startsWith(pattern + '/'));
    return { page: base ? '/' + base[0] + '/:detail' : '/unknown', label: base?.[1] || 'Other' };
}
export function detectBugLocation() {
    const route = routeLocation(location.pathname);
    const modals = Array.from(document.querySelectorAll<HTMLElement>('[data-bug-modal], [role="dialog"]')).filter(e => !e.closest('[data-bug-report]') && (e.getClientRects().length || Array.from(e.children).some(child => child.getClientRects().length)));
    const modal = modals[modals.length - 1];
    const heading = modal?.querySelector('h1,h2,h3');
    const name = modal?.getAttribute('data-bug-location') || heading?.textContent?.trim() || null;
    const scope = modal || document.querySelector('main') || document.body;
    const selected = scope.querySelector<HTMLElement>('button[aria-selected="true"], [role="tab"][aria-selected="true"], [data-bug-tab]');
    const tab = selected?.getAttribute('data-bug-tab') || selected?.textContent?.trim().slice(0, 100) || null;
    return { page: route.page, modal: name, tab, label: [route.label, name, tab].filter(Boolean).join(' → ') };
}
